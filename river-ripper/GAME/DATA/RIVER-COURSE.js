// How it was made, in case it needs regenerating:
//   1. Each tile is drawn to a canvas and reduced to 4x4-pixel cells.
//   2. Water mask: a cell is water when (B - R) >= 40 AND green-excess
//      (G - (R+B)/2) <= 5 AND mean luminance is between 45 and 140. Colour
