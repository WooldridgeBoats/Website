//   5. Each traced centreline is resampled to 120 even stations; heading
//      deltas and half-widths come off that. Position is thrown away -- only
//      curvature and width matter to the game -- which is why the six tiles
//      can simply be concatenated with no seam matching.
//   6. Curvature is scaled so the tightest bend stays under the point where
//      the bank geometry would fold, and widths are mapped onto the game's
//      width-multiplier range.
