#!/usr/bin/perl
# gen_new_inventory.pl - the New Boats (In Stock) pages, built like the Pre-Owned ones (Tyler 2026-11-04).
#
#   perl _build/gen_new_inventory.pl            # write everything
#   perl _build/gen_new_inventory.pl --check    # report what it would do, write nothing
#
# THE DATA IS _build/newinv.json (boats + dealers). Photos come from build_new_inventory.sh, which
# copies them to assets/newinv/<HULL>/ and then runs this. A boat shows once it has photos there.
#
# What it writes:
#   new-inventory/<slug>/index.html   one page per boat, from _build/newinv-boat-template.html (the
#                                     old single In Stock page): hero + rope stamp, write-up, gallery,
#                                     facts, price, buttons (a dealer boat's buttons are the dealer's)
#   new-inventory/index.html          the "New Boats" landing: Pre-Owned's card grid between the
#                                     <!-- NEWINV-GRID --> markers, green pill "In Stock" on each card
#   index.html                        the homepage New Boats card, between <!-- NEWINV-HOME --> markers
#   assets/instock.js                 WB_INSTOCK = boats shown (the In Stock menu link, main site + store)
# Then stamp_assets.pl, gen_canonicals.pl, gen_sitemap.pl (new pages need all three).
# A boat that's sold, removed or without photos has its page folder deleted, but only a folder
# whose index.html carries this script's GENERATED marker.
use strict;
use warnings;
use File::Basename qw(dirname);
use File::Path qw(make_path remove_tree);
use Cwd qw(abs_path);
use JSON::PP;
use Digest::MD5;

my $check = grep { $_ eq '--check' } @ARGV;
my $root  = dirname(dirname(abs_path(__FILE__)));
my $MARK  = '<!-- GENERATED by _build/gen_new_inventory.pl from _build/newinv.json - edit those, never this file -->';

sub slurp { my ($f) = @_; open my $fh, '<:raw', $f or die "can't read $f: $!"; local $/; my $d = <$fh>; close $fh; $d }
sub spew  { my ($f, $d) = @_; open my $fh, '>:raw', $f or die "can't write $f: $!"; print $fh $d; close $fh }
sub esc {
  my ($s) = @_; $s = '' unless defined $s;
  $s =~ s/&/&amp;/g; $s =~ s/</&lt;/g; $s =~ s/>/&gt;/g; $s =~ s/"/&quot;/g;
  $s =~ s/([^\x00-\x7f])/sprintf('&#%d;', ord $1)/ge;
  $s;
}
sub slugify { my $s = lc shift; $s =~ s/[^a-z0-9]+/-/g; $s =~ s/^-|-$//g; $s }

my $cfg     = JSON::PP->new->utf8->relaxed->decode(slurp("$root/_build/newinv.json"));
my %dealers = %{ $cfg->{dealers} || {} };
my @all     = @{ $cfg->{boats} || [] };
my $tpl     = slurp("$root/_build/newinv-boat-template.html");
my $header  = slurp("$root/header.html");
my $footer  = slurp("$root/footer.html");

# ---- which boats show ------------------------------------------------------------
my (@show, @problems);
for my $b (@all) {
  my $h = $b->{hull} // '';
  push(@problems, "a boat with no hull"), next unless $h =~ /^\d{4}$/;
  if ($b->{dealer} && !$dealers{ $b->{dealer} }) { push @problems, "$h: dealer '$b->{dealer}' isn't in dealers"; next }
  if ($b->{sold}) { print "  $h: sold - not shown\n"; next }
  my $dir = "$root/assets/newinv/$h";
  opendir(my $dh, $dir) or do { print "  $h: no photos yet (assets/newinv/$h) - not shown until build_new_inventory.sh brings them in\n"; next };
  my @nn = sort grep { /^\d\d\.jpg$/ } readdir $dh; closedir $dh;
  my @mm = -d "$dir/mobile" ? do { opendir my $m, "$dir/mobile"; my @x = sort grep { /^\d\d\.jpg$/ } readdir $m; @x } : ();
  unless (@nn && -f "$dir/hero.jpg") { print "  $h: photos incomplete (need hero.jpg + NN.jpg) - not shown\n"; next }
  for my $f (qw(len name price)) { push @problems, "$h: $f is empty" unless defined $b->{$f} && length $b->{$f} }
  my $md5 = Digest::MD5->new; $md5->addfile(do { open my $f, '<:raw', $_ or die; $f }) for (glob("$dir/*.jpg"), glob("$dir/thumbs/*.jpg"));
  $b->{_n} = @nn; $b->{_m} = @mm; $b->{_v} = substr($md5->hexdigest, 0, 8);
  $b->{_slug} = join '-', grep { length } ($b->{yr} // ''), 'wooldridge', $b->{len}, slugify($b->{name}), slugify($b->{cfg} // ''), $h;
  $b->{_d} = $b->{dealer} ? $dealers{ $b->{dealer} } : undef;
  push @show, $b;
}
if (@problems) { print "  ! $_\n" for @problems; die "fix _build/newinv.json first - nothing written\n" }

sub plain { my ($b) = @_; join ' ', grep { length } ($b->{yr} // ''), "$b->{len}'", $b->{name}, ($b->{cfg} // '') }
sub nice  { my ($b) = @_; join ' ', grep { length } ($b->{yr} // ''), "$b->{len}&prime;", esc($b->{name}) }
sub where { my ($b) = @_; $b->{_d} ? esc("$b->{_d}{name}, $b->{_d}{city}") : 'Wooldridge factory, Seattle, WA' }
sub tel   { my ($t) = @_; (my $d = $t) =~ s/[^\d]//g; "tel:+1$d" }
sub page  { "/new-inventory/$_[0]{_slug}/" }
sub vq    { "?v=$_[0]{_v}" }   # (not "q": that is Perl's quote operator)

# ---- one boat's page ------------------------------------------------------------
sub boat_page {
  my ($b) = @_;
  my %js = map { $_ => $b->{$_} } grep { !/^_/ && $_ ne 'dealer' } keys %$b;
  $js{dealer} = $b->{_d} ? { %{ $b->{_d} } } : undef; delete $js{dealer} unless $js{dealer};
  my $boatjs = JSON::PP->new->canonical->ascii->encode(\%js);
  $boatjs =~ s{</}{<\\/}g;
  my $photos = qq{<script>window.WB_NEWINV_PHOTOS={"$b->{hull}":{"n":$b->{_n},"m":$b->{_m},"v":"$b->{_v}"}};</script>};
  my $loc  = $b->{_d} ? esc($b->{_d}{city}) : 'Seattle, WA';
  my $kick = $b->{_d} ? 'IN STOCK &middot; AT OUR DEALER' : 'IN STOCK &middot; AT THE FACTORY';
  my $mast = qq{  <div class="crumb"><a href="/">HOME</a> / <a href="/new-inventory/">NEW BOATS</a> / } . nice($b) . qq{</div>\n}
           . qq{  <h1>} . nice($b) . qq{</h1><div class="kick">$kick</div><div class="tag">} . esc($b->{price}) . qq{ &nbsp;&middot;&nbsp; $loc</div>};
  my $desc = esc(plain($b) . ", Hull #$b->{hull}, in stock at " . ($b->{_d} ? "$b->{_d}{name}, $b->{_d}{city}" : 'the Wooldridge factory in Seattle') . ". $b->{price}.");
  my $t = $tpl;
  my %r = (__TITLE__ => esc(plain($b)) . ' &mdash; New Boats &mdash; Wooldridge Boats', __DESC__ => $desc, __PATH__ => page($b),
           __PHOTOS__ => $photos, __NEWINV__ => "\n    $boatjs\n  ", __MAST__ => $mast);
  for my $k (keys %r) { $t =~ s/\Q$k\E/$r{$k}/ or die "template has no $k\n" }
  $t =~ s{<!-- PARTIAL:header -->.*?<!-- /PARTIAL:header -->}{<!-- PARTIAL:header -->\n$header<!-- /PARTIAL:header -->}s or die "template has no header partial\n";
  $t =~ s{<!-- PARTIAL:footer -->.*?<!-- /PARTIAL:footer -->}{<!-- PARTIAL:footer -->\n$footer<!-- /PARTIAL:footer -->}s or die "template has no footer partial\n";
  $t =~ s{<head>\n}{<head>\n$MARK\n} or die "template has no <head>\n";
  $t;
}

# ---- one card on /new-inventory/ (Pre-Owned's card; pill "In Stock") --------------
sub card {
  my ($b) = @_;
  my $href = page($b);
  my @specs;
  push @specs, '<span><b>Engine:</b> ' . esc($b->{eng}) . '</span>' if $b->{eng};
  push @specs, '<span><b>Location:</b> ' . where($b) . '</span>';
  push @specs, '<span><b>Hull:</b> #' . esc($b->{hull}) . '</span>';
  my ($name, $phone) = $b->{_d} ? ($b->{_d}{name}, $b->{_d}{tel}) : ('Wooldridge Boats', '(206) 722-8998');
  push @specs, '<span><b>Contact:</b> <b>' . esc($name) . '</b> &middot; <a href="' . tel($phone) . '">' . esc($phone) . '</a></span>';
  my $n = $b->{_n};
  return join '',
    '<article class="inv polist" data-href="' . $href . '">',
      '<a class="invph" href="' . $href . '" aria-label="' . esc(plain($b)) . ' - open the boat\'s page"><span class="badge in">In Stock</span>',
        '<img src="/assets/newinv/' . $b->{hull} . '/thumbs/hero.jpg' . vq($b) . '" alt="' . esc(plain($b)) . ', Hull ' . $b->{hull} . '" loading="lazy"></a>',
      '<div class="ibody"><div class="iyear">' . join(' &middot; ', grep { length } (esc($b->{yr} // ''), esc($b->{drive} // ''))) . '</div>',
        '<h3><a href="' . $href . '">' . $b->{len} . '&prime; ' . esc($b->{name}) . ($b->{cfg} ? ' ' . esc($b->{cfg}) : '') . '</a></h3>',
        '<div class="specs">' . join('', @specs) . '</div>',
        '<div class="irow"><span class="iprice">' . esc($b->{price}) . '</span>',
          '<a class="ilink" href="' . $href . '">' . $n . ' photo' . ($n == 1 ? '' : 's') . ' &middot; View boat &rsaquo;</a></div></div>',
    '</article>';
}

# ---- the homepage New Boats card (first boat shown) ------------------------------
sub home_card {
  my $b = $show[0] or return qq{        <div class="listings newinv-row">\n          <p class="newinv-note">New boats ready to run show up here as they come off the line. Call the shop at <a href="tel:+12067228998">(206)&nbsp;722-8998</a>.</p>\n        </div>\n};
  my $blurb = esc($b->{eng} ? "$b->{eng}. " : '') . ($b->{_d} ? 'Ready now at ' . esc($b->{_d}{name}) . ', ' . esc($b->{_d}{city}) : 'Ready now at the factory') . ", Hull #$b->{hull}.";
  my $more = @show > 1 ? scalar(@show) . ' new boats in stock right now, at the factory and with our dealers.' : 'Skip the build queue &mdash; completed boats ready to run, at the factory and with our dealers.';
  return qq{        <div class="listings newinv-row">\n}
    . qq{          <a class="listing" href="} . page($b) . qq{">\n}
    . qq{            <div class="nm">} . ($b->{yr} ? esc($b->{yr}) . ' ' : '') . qq{$b->{len}&prime; } . esc($b->{name}) . ($b->{cfg} ? ' ' . esc($b->{cfg}) : '') . qq{</div>\n}
    . qq{            <img src="assets/newinv/$b->{hull}/thumbs/hero.jpg} . vq($b) . qq{" alt="} . esc(plain($b)) . qq{, hull $b->{hull}, in stock" loading="lazy">\n}
    . qq{            <div class="blurbsm">$blurb</div>\n}
    . qq{            <div class="price">} . esc($b->{price}) . qq{</div>\n}
    . qq{          </a>\n}
    . qq{          <p class="newinv-note">$more Availability changes week to week; the current list is on the New Boats page, or call the shop at <a href="tel:+12067228998">(206)&nbsp;722-8998</a>.</p>\n}
    . qq{        </div>\n};
}

# ---- report ----------------------------------------------------------------------
print "New Boats: " . scalar(@show) . " boat(s) shown\n";
printf "  %-55s %s\n", page($_), plain($_) . ' - ' . ($_->{_d} ? $_->{_d}{name} : 'factory') . " - $_->{_n} photos" for @show;
exit 0 if $check && print "[check] nothing written\n";

# ---- write ------------------------------------------------------------------------
my %want;
for my $b (@show) {
  my $dir = "$root/new-inventory/$b->{_slug}";
  make_path($dir); spew("$dir/index.html", boat_page($b)); $want{ $b->{_slug} } = 1;
}
opendir my $nd, "$root/new-inventory" or die;
for my $d (grep { !/^\./ && -d "$root/new-inventory/$_" && !$want{$_} } readdir $nd) {
  my $f = "$root/new-inventory/$d/index.html";
  if (-f $f && slurp($f) =~ /\Q$MARK\E/) { remove_tree("$root/new-inventory/$d"); print "  removed /new-inventory/$d/ (sold, removed or no photos)\n" }
}
closedir $nd;

my $grid = !@show
  ? qq{<div class="infocard"><h3>Nothing in stock this week</h3><p style="font-weight:400; font-size:14px; margin:6px 0 0;">New boats ready to run show up here as they come off the line. Every Wooldridge is built to order, so price yours in Build &amp; Price below, or call the shop at <a href="tel:+12067228998">(206)&nbsp;722-8998</a>.</p></div>\n}
  : qq{<div class="listing-grid" id="grid">\n} . join("\n", map { card($_) } @show) . qq{\n</div>\n};
my $land = slurp("$root/new-inventory/index.html");
$land =~ s{(<!-- NEWINV-GRID -->\n).*?(<!-- /NEWINV-GRID -->)}{$1$MARK\n$grid$2}s or die "no NEWINV-GRID markers in new-inventory/index.html\n";
spew("$root/new-inventory/index.html", $land);

my $home = slurp("$root/index.html");
$home =~ s{(<!-- NEWINV-HOME[^\n]*-->\n).*?([ \t]*<!-- /NEWINV-HOME -->)}{$1 . home_card() . $2}se or die "no NEWINV-HOME markers in index.html\n";
spew("$root/index.html", $home);

my $is = slurp("$root/assets/instock.js");
my $cnt = @show;
$is =~ s/window\.WB_INSTOCK = \d+;/window.WB_INSTOCK = $cnt;/ or die "no WB_INSTOCK in assets/instock.js\n";
spew("$root/assets/instock.js", $is);
print "  In Stock menu link: " . ($cnt ? "ON ($cnt shown)" : 'OFF') . "\n";

for my $s (qw(stamp_assets.pl gen_canonicals.pl gen_sitemap.pl)) {
  system('perl', "$root/_build/$s") == 0 or die "$s failed\n";
}
print "DONE. Check /new-inventory/ and each boat page at 1440 + 390 / 360 / 320, then commit with explicit paths.\n";
