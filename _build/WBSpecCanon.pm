# plus two report tabs the extractor writes (SPEC DISCREPANCIES, SPEC PROVENANCE)
# that these tools carry through but never read for generation.
#
# Surfaces driven from the canon (all in the website repo):
#   build-and-price/index.html   the "std" array of every model in const MODELS
#   tools/STD_DATA.js            regenerated by _build/gen_std_data.pl afterwards
#   models/<slug>/index.html     <!-- STD:slug --> grid, <!-- SPECS:slug --> block,
