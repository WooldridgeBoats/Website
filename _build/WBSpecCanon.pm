# ------------------------------------------------------------------ files ----
sub slurp_bytes { my ($p) = @_; open my $fh, '<:raw', $p or die "cannot read $p: $!\n"; local $/; my $b = <$fh>; close $fh; return $b }
sub slurp_text {                     # bytes -> characters, BOM dropped, CRLF -> LF; returns (text, eol)
  my ($p) = @_;
  my $b = slurp_bytes($p);
  my $eol = detect_eol($b);
  my $s = decode('UTF-8', $b, Encode::FB_CROAK);
  $s =~ s/^\x{FEFF}//;
  $s =~ s/\r\n/\n/g;
  return wantarray ? ($s, $eol) : $s;
}
sub detect_eol { my ($b) = @_; return ($b =~ /\r\n/) ? "\r\n" : "\n" }
sub write_text {                     # characters with \n -> file with the given eol, UTF-8, no BOM
  my ($p, $s, $eol) = @_;
  $eol = "\n" unless defined $eol;
  (my $t = $s) =~ s/\n/$eol/g if $eol ne "\n";
  $t = $s if $eol eq "\n";
  open my $fh, '>:raw', $p or die "cannot write $p: $!\n";
  print $fh encode('UTF-8', $t);
  close $fh;
}

# -------------------------------------------------------------------- CSV ----
sub csv_field {                      # same quoting rule as merge_spec_tabs.ps1's dump: quote only when needed
  my ($v) = @_;
  $v = '' unless defined $v;
  if ($v =~ /[",\r\n]/) { $v =~ s/"/""/g; return qq{"$v"} }
  return $v;
}
sub csv_text {                       # (\@header, \@rows of arrays) -> text (LF)
  my ($hdr, $rows) = @_;
  return join('', map { join(',', map { csv_field($_) } @$_) . "\n" } ($hdr, @$rows));
}
sub parse_csv_text {                 # RFC 4180 -> (\@header, \@rows of arrays); blank lines dropped
  my ($s, $what) = @_;
  $what = 'CSV' unless defined $what;
  $s =~ s/^\x{FEFF}//;
  my (@rows, @row); my $f = ''; my $inq = 0; my $n = length $s; my $k = 0;
  while ($k < $n) {
    my $c = substr($s, $k, 1);
    if ($inq) {
      if ($c eq '"') {
        if (substr($s, $k + 1, 1) eq '"') { $f .= '"'; $k += 2; next }
        $inq = 0; $k++; next;
      }
      $f .= $c; $k++; next;
    }
    if ($c eq '"') { $inq = 1; $k++; next }
    if ($c eq ',') { push @row, $f; $f = ''; $k++; next }
    if ($c eq "\n" || $c eq "\r") {
      push @row, $f; push @rows, [@row]; @row = (); $f = '';
      $k++; $k++ if $c eq "\r" && substr($s, $k, 1) eq "\n";
      next;
    }
    $f .= $c; $k++;
  }
  die "$what: unterminated quoted field\n" if $inq;
  if (length $f || @row) { push @row, $f; push @rows, [@row] }
  @rows = grep { !(@$_ == 1 && $_->[0] eq '') } @rows;
  my $hdr = shift @rows or die "$what: empty\n";
  return ($hdr, \@rows);
}
sub read_csv {                       # path -> (\@header, \@records as hashes)
  my ($p) = @_;
  my ($hdr, $rows) = parse_csv_text(scalar slurp_text($p), $p);
  return ($hdr, [ map { my %h; @h{@$hdr} = map { defined $_ ? $_ : '' } @$_[0 .. $#$hdr]; \%h } @$rows ]);
}

# ------------------------------------------------------------------- XLSX ----
sub xml_unent {
  my ($s) = @_;
  return '' unless defined $s;
  $s =~ s/&#x([0-9a-fA-F]+);/chr(hex $1)/ge;
  $s =~ s/&#(\d+);/chr($1)/ge;
  $s =~ s/&lt;/</g; $s =~ s/&gt;/>/g; $s =~ s/&quot;/"/g; $s =~ s/&apos;/'/g; $s =~ s/&amp;/&/g;
  return $s;
}
sub xlsx_member {
  my ($file, $name) = @_;
  my $u = IO::Uncompress::Unzip->new($file, Name => $name) or return undef;
  local $/; my $d = <$u>; close $u;
  return decode('UTF-8', defined $d ? $d : '');
}
sub col_index { my ($l) = @_; my $i = 0; $i = $i * 26 + (ord($_) - 64) for split //, uc $l; return $i - 1 }
sub num_str { my ($v) = @_; return $v unless $v =~ /^[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?$/; my $n = 0 + $v; return "$n" }
sub t_runs {                         # join every <t> run inside a fragment, phonetic runs dropped
  my ($x) = @_;
  $x =~ s{<rPh\b.*?</rPh>}{}gs;
  return join('', map { xml_unent($_) } $x =~ m{<t\b[^>]*>(.*?)</t>|<t\b[^>]*/>()}gs);
}
sub read_xlsx_tabs {                 # path -> { tab name => [ [cell strings...], ... ] }
  my ($file) = @_;
  die "xlsx not found: $file\n" unless -f $file;
  my $wb = xlsx_member($file, 'xl/workbook.xml');
  die "$file: no xl/workbook.xml ($UnzipError)\n" unless defined $wb;
  my $rels = xlsx_member($file, 'xl/_rels/workbook.xml.rels');
  die "$file: no xl/_rels/workbook.xml.rels\n" unless defined $rels;
  my %target;
  while ($rels =~ /<Relationship\b([^>]*?)\/?>/g) {
    my $a = $1;
    my ($id) = $a =~ /\bId="([^"]*)"/; my ($t) = $a =~ /\bTarget="([^"]*)"/;
    next unless defined $id && defined $t;
    $t = $t =~ m{^/} ? substr($t, 1) : "xl/$t";
    $target{$id} = xml_unent($t);
  }
  my @shared;
  my $ss = xlsx_member($file, 'xl/sharedStrings.xml');
  if (defined $ss) { push @shared, t_runs($1) while $ss =~ m{<si>(.*?)</si>}gs }
  my %tabs;
  while ($wb =~ /<sheet\b([^>]*?)\/?>/g) {
    my $a = $1;
    my ($name) = $a =~ /\bname="([^"]*)"/; my ($rid) = $a =~ /\b(?:\w+:)?id="([^"]*)"/;
    next unless defined $name && defined $rid;
    $name = xml_unent($name);
    my $path = $target{$rid} or die "$file: sheet '$name' has no relationship target for $rid\n";
    my $xml = xlsx_member($file, $path);
    die "$file: sheet '$name' member $path missing\n" unless defined $xml;
    my @grid;
    while ($xml =~ m{<row\b([^>]*)>(.*?)</row>}gs) {
      my ($ra, $body) = ($1, $2);
      my ($rn) = $ra =~ /\br="(\d+)"/;
      my @cells;
      while ($body =~ m{<c\b([^>]*?)(?:/>|>(.*?)</c>)}gs) {
        my ($ca, $cb) = ($1, defined $2 ? $2 : '');
        my ($ref) = $ca =~ /\br="([A-Z]+)\d+"/; next unless defined $ref;
        my ($t)   = $ca =~ /\bt="([^"]*)"/; $t = '' unless defined $t;
        my $v = '';
        if ($t eq 's')            { my ($i) = $cb =~ m{<v>(.*?)</v>}s; $v = defined $i && defined $shared[$i] ? $shared[$i] : '' }
        elsif ($t eq 'inlineStr') { $v = t_runs($cb) }
        elsif ($t eq 'b')         { my ($b) = $cb =~ m{<v>(.*?)</v>}s; $v = (defined $b && $b eq '1') ? 'TRUE' : 'FALSE' }
        else                      { my ($x) = $cb =~ m{<v>(.*?)</v>}s; $v = defined $x ? xml_unent($x) : ''; $v = num_str($v) if $t eq '' }
        $cells[col_index($ref)] = $v;
      }
      $_ = '' for grep { !defined } @cells;   # no-op guard
      @cells = map { defined $_ ? $_ : '' } @cells;
      next unless grep { length } @cells;
      push @grid, \@cells;
    }
    $tabs{$name} = \@grid;
  }
  return \%tabs;
}
sub tabs_to_csv_text {               # a tab grid -> CSV text in the extractor's exact format
  my ($grid, $name) = @_;
  die "tab '$name' is empty\n" unless @$grid;
  my @g = map { [@$_] } @$grid;
  my $hdr = shift @g;
  pop @$hdr while @$hdr && $hdr->[-1] eq '';
  my $w = @$hdr;
  for my $r (@g) { push @$r, '' while @$r < $w; pop @$r while @$r > $w && $r->[-1] eq '' }
  return csv_text($hdr, \@g);
}

# ------------------------------------------------------------- the canon ----
sub load_canon {                     # folder of CSVs -> canon structure
  my ($dir) = @_;
  my %texts;
  for my $t (DRIVEN_TABS) { my $p = "$dir/$t.csv"; die "canon file missing: $p\n" unless -f $p; $texts{$t} = scalar slurp_text($p) }
  return load_canon_from_tabs(\%texts);
}
sub load_canon_from_tabs {           # { tab => CSV text } -> canon structure (validated)
  my ($texts) = @_;
  my %T;
  for my $t (DRIVEN_TABS) {
    die "canon tab missing: $t\n" unless defined $texts->{$t};
    my ($hdr, $rows) = parse_csv_text($texts->{$t}, $t);
    $T{$t} = [ map { my %h; @h{@$hdr} = map { defined $_ ? $_ : '' } @$_[0 .. $#$hdr]; \%h } @$rows ];
  }
  my %C = (lineup => [], by_id => {}, std => {}, specs => {}, desc => {});
  for my $r (sort { $a->{sort_order} <=> $b->{sort_order} } @{ $T{'LINEUP'} }) {
    for my $k (qw(model_id model_name page_slug photo_slug sort_order)) { die "LINEUP: '$k' empty on row for '$r->{model_id}'\n" unless length $r->{$k} }
    die "LINEUP: duplicate model_id '$r->{model_id}'\n" if $C{by_id}{$r->{model_id}};
    push @{ $C{lineup} }, $r; $C{by_id}{$r->{model_id}} = $r;
  }
  die "LINEUP: no CURRENT models\n" unless @{ $C{lineup} };
  for my $r (sort { $a->{group_order} <=> $b->{group_order} || $a->{item_order} <=> $b->{item_order} } @{ $T{'STD FEATURES'} }) {
    my $id = $r->{model_id};
    die "STD FEATURES: model_id '$id' is not in LINEUP\n" unless $C{by_id}{$id};
    my $g = $C{std}{$id} ||= [];
    my $gi = $r->{group_order} - 1;
    $g->[$gi] ||= { h => $r->{group_heading}, items => [] };
    die "STD FEATURES: $id group $r->{group_order} has two headings ('$g->[$gi]{h}' vs '$r->{group_heading}')\n" if $g->[$gi]{h} ne $r->{group_heading};
    push @{ $g->[$gi]{items} }, { t => $r->{item_text}, tag => $r->{config_tag} };
  }
  for my $id (keys %{ $C{std} }) { for my $i (0 .. $#{ $C{std}{$id} }) { die "STD FEATURES: $id has a gap at group " . ($i + 1) . "\n" unless $C{std}{$id}[$i] } }
  for my $r (@{ $T{'DESCRIPTIONS'} }) {
    die "DESCRIPTIONS: model_id '$r->{model_id}' is not in LINEUP\n" unless $C{by_id}{$r->{model_id}};
    $C{desc}{$r->{model_id}}{$r->{field}} = $r->{text};
  }
  for my $r (@{ $T{'SPECS'} }) {
    my $id = $r->{model_id};
    die "SPECS: model_id '$id' is not in LINEUP\n" unless $C{by_id}{$id};
    my $s = $C{specs}{$id} ||= { lengths => [], len_idx => {}, categories => [], cat_idx => {} };
    unless (exists $s->{len_idx}{$r->{length_ft}}) { $s->{len_idx}{$r->{length_ft}} = @{ $s->{lengths} }; push @{ $s->{lengths} }, $r->{length_ft} }
    my $li = $s->{len_idx}{$r->{length_ft}};
    unless (exists $s->{cat_idx}{$r->{category}}) { $s->{cat_idx}{$r->{category}} = @{ $s->{categories} }; push @{ $s->{categories} }, { name => $r->{category}, rows => [], row_idx => {} } }
    my $cat = $s->{categories}[ $s->{cat_idx}{$r->{category}} ];
    unless (exists $cat->{row_idx}{$r->{field}}) { $cat->{row_idx}{$r->{field}} = @{ $cat->{rows} }; push @{ $cat->{rows} }, { label => $r->{field}, cells => [] } }
    my $row = $cat->{rows}[ $cat->{row_idx}{$r->{field}} ];
    my $lay = $r->{layout} || 'plain';
    die "SPECS: $id '$r->{field}' layout '$lay' unknown (plain, badge, list)\n" unless $lay =~ /^(plain|badge|list)$/;
    $row->{layout} = $lay unless defined $row->{layout};
    die "SPECS: $id '$r->{field}' mixes layouts ($row->{layout} vs $lay)\n" if ($row->{layout} eq 'list') ne ($lay eq 'list');
    if ($lay eq 'list') { push @{ $row->{cells}[$li] ||= [] }, [ $r->{note}, $r->{value_text} ] }
    else {
      die "SPECS: $id '$r->{field}' has two values for $r->{length_ft} ft\n" if defined $row->{cells}[$li];
      $row->{cells}[$li] = $lay eq 'badge' || length $r->{note} ? { v => $r->{value_text}, badge => $r->{note} } : $r->{value_text};
    }
  }
  for my $id (keys %{ $C{specs} }) {
    my $s = $C{specs}{$id};
    for my $cat (@{ $s->{categories} }) { for my $row (@{ $cat->{rows} }) { for my $i (0 .. $#{ $s->{lengths} }) {
      die "SPECS: $id '$row->{label}' has no value for $s->{lengths}[$i] ft\n" unless defined $row->{cells}[$i];
    } } }
  }
  return \%C;
}
sub fmt_len { my ($l) = @_; return "$l ft." }

# ---------------------------------------------------------- renderers ----
sub js_str {                         # the configurator's JSON string style: ASCII, \uXXXX lowercase, / unescaped
  my ($s) = @_;
  $s = '' unless defined $s;
  $s =~ s/\\/\\\\/g; $s =~ s/"/\\"/g;
  $s =~ s/([\x00-\x1f])/sprintf('\\u%04x', ord $1)/ge;
  $s =~ s/([^\x00-\x7f])/ord($1) > 0xFFFF ? sprintf('\\u%04x\\u%04x', 0xD800 + ((ord($1) - 0x10000) >> 10), 0xDC00 + ((ord($1) - 0x10000) & 0x3FF)) : sprintf('\\u%04x', ord $1)/ge;
  return qq{"$s"};
}
sub render_std_json {                # [ {h, items=>[{t,tag}]} ] -> the exact "std" array text
  my ($groups) = @_;
  return '[' . join(',', map {
    '{"h":' . js_str($_->{h}) . ',"items":[' . join(',', map {
      '{"t":' . js_str($_->{t}) . (defined $_->{tag} && length $_->{tag} ? ',"tag":' . js_str($_->{tag}) : '') . '}'
    } @{ $_->{items} }) . ']}'
  } @$groups) . ']';
}
# --- const MODELS, written PER FIELD ----------------------------------------
# The configurator's const MODELS is one 376 KB JSON line that nothing else
# may reformat (other generators and the SOC sync read it by shape). So a
# canon-driven field is written by SPLICING: locate the exact character span
# of that top-level member in each model object and replace just that span
# with the canon's rendering in the line's own style (js_str: ASCII, \uXXXX
# lowercase, "/" unescaped). An unchanged canon therefore yields an identical
# line, byte for byte.
#
# HOW A SECOND FIELD WRITER PLUGS IN (the pricing phase, later) - no
# restructuring needed:
#   my $spans = models_field_spans($line, \@ids, 'styles');   # or 'engines', 'lengths', ...
#   for my $sp (@$spans) { $want = render_<field>($canon...); splice as gen_from_canon.pl section 1 does }
# models_field_spans() returns the span of ANY top-level member of each model
# object (string, number, array or object value), found by a real walk of the
# object at depth 1, so nested keys of the same name can never be mistaken for
# it. Write a render_<field>() that emits the member's value in the same JSON
# style, and splice spans from the END of the line backwards (or rebuild the
# line left to right as section 1 does) so earlier offsets stay valid.
# NOTHING here knows about prices today; models_std_spans() is the std wrapper.
sub value_end {                      # index of the last character of the JSON value starting at $i
  my ($line, $i) = @_;
  my $n = length $line;
  my $c = substr($line, $i, 1);
  if ($c eq '"') {
    my $j = $i + 1;
    while ($j < $n) { my $d = substr($line, $j, 1); if ($d eq "\\") { $j += 2; next } return $j if $d eq '"'; $j++ }
    die "const MODELS: unterminated string at $i\n";
  }
  if ($c eq '[' || $c eq '{') {
    my ($depth, $instr) = (0, 0);
    for (my $j = $i; $j < $n; $j++) {
      my $d = substr($line, $j, 1);
      if ($instr) { if ($d eq "\\") { $j++; next } $instr = 0 if $d eq '"'; next }
      if ($d eq '"') { $instr = 1; next }
      if ($d eq '[' || $d eq '{') { $depth++ } elsif ($d eq ']' || $d eq '}') { $depth--; return $j if $depth == 0 }
    }
    die "const MODELS: unbalanced value at $i\n";
  }
  my $j = $i;                         # number / true / false / null
  $j++ while $j < $n && substr($line, $j, 1) !~ /[,\]}]/;
  return $j - 1;
}
sub model_top_fields {               # object starting at $p -> ({ key => {start,len} } of its depth-1 members, index of its '}')
  my ($line, $p) = @_;
  die "const MODELS: expected '{' at $p\n" unless substr($line, $p, 1) eq '{';
  my $n = length $line; my $i = $p + 1; my %f;
  while ($i < $n) {
    my $c = substr($line, $i, 1);
    if ($c eq '}') { return (\%f, $i) }
    if ($c eq ',' || $c =~ /\s/) { $i++; next }
    die "const MODELS: expected a key at $i, found '$c'\n" unless $c eq '"';
    my $ke = value_end($line, $i);
    my $key = substr($line, $i + 1, $ke - $i - 1);
    $i = $ke + 1;
    $i++ while substr($line, $i, 1) =~ /\s/;
    die "const MODELS: expected ':' after key '$key'\n" unless substr($line, $i, 1) eq ':';
    $i++; $i++ while substr($line, $i, 1) =~ /\s/;
    my $ve = value_end($line, $i);
    die "const MODELS: key '$key' appears twice in one model object\n" if $f{$key};
    $f{$key} = { start => $i, len => $ve - $i + 1 };
    $i = $ve + 1;
  }
  die "const MODELS: unterminated model object at $p\n";
}
sub models_field_spans {             # (line, [ids in line order], field) -> [ {id, start, len} ] of that top-level member per model
  my ($line, $ids, $field) = @_;
  my @spans; my $cur = 0;
  for my $id (@$ids) {
    my $lit = '{"id":' . js_str($id) . ',"nm":';
    my $p = index($line, $lit, $cur);
    die "const MODELS: model '$id' not found after offset $cur\n" if $p < 0;
    my ($f, $end) = model_top_fields($line, $p);
    die "const MODELS: model '$id' has no top-level \"$field\" member\n" unless $f->{$field};
    push @spans, { id => $id, start => $f->{$field}{start}, len => $f->{$field}{len} };
    $cur = $end + 1;
  }
  return \@spans;
}
sub models_std_spans { my ($line, $ids) = @_; return models_field_spans($line, $ids, 'std') }
sub render_stdgrid {                 # groups -> the page's one-line grid (no indent, raw text, no escaping - the page convention)
  my ($groups) = @_;
  return '<div class="stdgrid">' . join('', map {
    '<div class="stdsec"><h3>' . $_->{h} . '</h3><ul>' . join('', map {
      '<li>' . $_->{t} . (defined $_->{tag} && length $_->{tag} ? ' <span class="q">(' . $_->{tag} . ')</span>' : '') . '</li>'
    } @{ $_->{items} }) . '</ul></div>'
  } @$groups) . '</div>';
}
sub esc { my ($s) = @_; $s = '' unless defined $s; $s =~ s/&/&amp;/g; $s =~ s/</&lt;/g; $s =~ s/>/&gt;/g; return $s }
sub render_specs_block {             # port of _build/build_specs.py build_block(): same bytes for the same data
  my ($slug, $s, $d) = @_;           # $s = canon specs structure, $d = descriptions hash for the model
  my @L = map { fmt_len($_) } @{ $s->{lengths} };
  my $n = @L; my $colspan = $n + 1;
  my $summary = (defined $d->{specs_summary} && length $d->{specs_summary}) ? esc($d->{specs_summary}) : 'Dimensions, Weight &amp; Power';
  my $intro   = esc((defined $d->{specs_intro} && length $d->{specs_intro}) ? $d->{specs_intro} : 'Configuration-specific differences are labeled below.');
  my $name    = esc(defined $d->{specs_name} && length $d->{specs_name} ? $d->{specs_name} : '');
  my $foot    = (defined $d->{specs_footnote} && length $d->{specs_footnote}) ? '      <p class="bspec-foot">' . esc($d->{specs_footnote}) . "</p>\n" : '';
  my @tabs = ('      <div class="bspec-lentabs" role="tablist" aria-label="Choose a length">');
  for my $i (1 .. $n) {
    push @tabs, sprintf('        <button type="button" class="bspec-lentab%s" data-idx="%d" role="tab" aria-selected="%s">%s</button>',
                        $i == 1 ? ' is-active' : '', $i, $i == 1 ? 'true' : 'false', esc($L[$i - 1]));
  }
  push @tabs, '      </div>';
  my $cols = '<col class="bspec-c0">' . ('<col>' x $n);
  my $th = '<th scope="col" class="bspec-spec">Specification</th>' . join('', map { sprintf('<th scope="col" class="bspec-v bspec-v%d">%s</th>', $_, esc($L[$_ - 1])) } 1 .. $n);
  my @rows;
  for my $cat (@{ $s->{categories} }) {
    push @rows, sprintf('            <tr class="bspec-cat"><th colspan="%d" scope="colgroup"><span>%s</span></th></tr>', $colspan, esc($cat->{name}));
    for my $row (@{ $cat->{rows} }) {
      my $cells = '';
      for my $i (1 .. $n) {
        my $c = $row->{cells}[$i - 1]; my $cls = "bspec-v bspec-v$i";
        if ($row->{layout} eq 'list') {
          $cells .= qq{<td class="$cls"><ul class="bspec-wt">} . join('', map { '<li><span class="bspec-badge">' . esc($_->[0]) . '</span><span class="v">' . esc($_->[1]) . '</span></li>' } @$c) . '</ul></td>';
        } elsif (ref $c) {
          $cells .= qq{<td class="$cls"><span class="bspec-cell">} . esc($c->{v}) . ' <span class="bspec-dot" aria-hidden="true">&middot;</span> <span class="bspec-badge">' . esc($c->{badge}) . '</span></span></td>';
        } else {
          $cells .= qq{<td class="$cls">} . esc($c) . '</td>';
        }
      }
      push @rows, '            <tr><th scope="row">' . esc($row->{label}) . '</th>' . $cells . '</tr>';
    }
  }
  return "  <!-- SPECS:$slug -->\n"
       . "  <div class=\"sechead tight\"><div class=\"eyebrow\">Model Details</div>\n"
       . "        <h2 style=\"font-size:clamp(20px,2.6vw,28px);\">Boat Specifications</h2>\n"
       . "        <p class=\"lede\">$intro</p></div>\n"
       . "  <details class=\"pfold bspecfold\">\n"
       . "    <summary><span class=\"pfoldeyebrow\">Full Specs</span><span class=\"pfoldtitle\">$summary</span><span class=\"pfoldchev\" aria-hidden=\"true\"></span></summary>\n"
       . "    <div class=\"pfoldbody\">\n"
       . join("\n", @tabs) . "\n"
       . "      <div class=\"bspec-scroll\">\n"
       . "        <table class=\"bspec\">\n"
       . "          <caption>$name specifications by length</caption>\n"
       . "          <colgroup>$cols</colgroup>\n"
       . "          <thead>\n"
       . "            <tr>$th</tr>\n"
       . "          </thead>\n"
       . "          <tbody>\n"
       . join("\n", @rows) . "\n"
       . "          </tbody>\n"
       . "        </table>\n"
       . "      </div>\n"
       . "$foot    </div>\n"
       . "  </details>\n"
       . "  <!-- /SPECS -->";
}
sub tagline_html { my ($t) = @_; return '<div class="tag">' . $t . '</div>' }
sub intro_html   { my ($t) = @_; return '<p style="font-size:16px; line-height:1.7;">' . $t . '</p>' }
sub camel { my ($s) = @_; my @w = grep { length } split /[^A-Za-z0-9]+/, $s; return '' unless @w; return lc(shift @w) . join('', map { ucfirst $_ } @w) }
sub render_spec_data_js {            # canon -> tools/SPEC_DATA.js text (LF); shape consumed by compare/index.html
  my ($C) = @_;
  my (@groups, %gidx, %kseen);
  my %data;
  for my $m (@{ $C->{lineup} }) {
    my $id = $m->{model_id}; my $s = $C->{specs}{$id} or next;
    for my $cat (@{ $s->{categories} }) {
      unless (exists $gidx{$cat->{name}}) { $gidx{$cat->{name}} = @groups; push @groups, [ $cat->{name}, [] ] }
      my $keys = $groups[ $gidx{$cat->{name}} ][1];
      for my $row (@{ $cat->{rows} }) {
        for my $i (0 .. $#{ $s->{lengths} }) {
          my $len = $s->{lengths}[$i]; my $c = $row->{cells}[$i];
          my @kv = $row->{layout} eq 'list'
                 ? map { [ camel("$row->{label} $_->[0]"), "$row->{label} ($_->[0])", $_->[1] ] } @$c
                 : ref $c ? [ camel($row->{label}), $row->{label}, "$c->{v} ($c->{badge})" ]
                          : [ camel($row->{label}), $row->{label}, $c ];
          for my $kv (@kv) {
            unless ($kseen{$cat->{name}}{$kv->[0]}++) { push @$keys, [ $kv->[0], $kv->[1] ] }
            $data{$id}{$len}{$kv->[0]} = $kv->[2];
          }
        }
      }
    }
  }
  my $J = JSON::PP->new->ascii;
  my $out = "/* SPEC_DATA.js - GENERATED by _build/gen_from_canon.pl from the informational canon's\n"
          . "   SPECS tab (SPECS.csv): the figures the model pages publish, one key per published row.\n"
          . "   The shop spec worksheets (_build/gen_spec_data.ps1) are NO LONGER the source of this file\n"
          . "   as of 2026-10-13 - the website as published is the day-one truth (Stephen, 2026-10-10).\n"
          . "   Do not hand-edit: change the canon and re-run perl _build/gen_from_canon.pl.\n"
          . "   Consumed by compare/index.html (WB_SPEC_GROUPS + WB_SPECS). */\n"
          . "const WB_SPEC_GROUPS = [\n"
          . join(",\n", map { '  [' . $J->encode($_->[0]) . ', [' . join(',', map { '[' . $J->encode($_->[0]) . ',' . $J->encode($_->[1]) . ']' } @{ $_->[1] }) . ']]' } @groups) . "\n"
          . "];\n"
          . "const WB_SPECS = {\n";
  my @m;
  for my $m (@{ $C->{lineup} }) {
    my $id = $m->{model_id}; my $d = $data{$id} || {};
    my @lens = sort { $a <=> $b } keys %$d;
    push @m, '  ' . $J->encode($id) . ": {\n" . join(",\n", map {
      my $len = $_; '    ' . $J->encode($len) . ': {' . join(',', map { $J->encode($_) . ':' . $J->encode($d->{$len}{$_}) } sort keys %{ $d->{$len} }) . '}'
    } @lens) . "\n  }";
  }
  $out .= join(",\n", @m) . "\n};\n";
  return $out;
}

# ------------------------------------------------------- surface checks ----
# Returns [ { surface, models, mismatches, first } ] comparing the repo's
# current surfaces to what the canon would render. Read-only. Used by the
# verifier (table + exit code) and by the generator's --dry-run.
sub first_diff {                     # two strings -> short quoted description of where they differ
  my ($a, $b) = @_;
  my $n = length($a) < length($b) ? length($a) : length($b);
  my $i = 0; $i++ while $i < $n && substr($a, $i, 1) eq substr($b, $i, 1);
  my $ctx = sub { my ($s) = @_; my $f = substr($s, $i < 25 ? 0 : $i - 25, 70); $f =~ s/\n/\\n/g; return $f };
  return 'at char ' . ($i + 1) . ': expected "' . $ctx->($a) . '" got "' . $ctx->($b) . '"';
}
sub check_surfaces {
  my ($repo, $C) = @_;
  my @ids = map { $_->{model_id} } @{ $C->{lineup} };
  my @R;
  my $add = sub { my ($name, $models, $mm, $first) = @_; push @R, { surface => $name, models => $models, mismatches => $mm, first => $first // '' } };

  # 1. configurator const MODELS std
  {
    my ($cfg) = slurp_text("$repo/build-and-price/index.html");
    my @ml = grep { /^\s*const MODELS = / } split /\n/, $cfg;
    if (@ml != 1) { $add->('configurator: const MODELS std', scalar @ids, scalar @ids, 'const MODELS line count ' . scalar(@ml)) }
    else {
      my $line = $ml[0];
      my $json = JSON::PP->new->decode(($line =~ s/^\s*const MODELS = //r) =~ s/;\s*$//r);
      my @cids = map { $_->{id} } @$json;
      my @extra = grep { !$C->{by_id}{$_} } @cids;
      my $mm = 0; my $first;
      if (@extra) { $mm = scalar @extra; $first = 'configurator models not in LINEUP: ' . join(',', @extra) }
      else {
        my $spans = models_std_spans($line, \@cids);
        for my $sp (@$spans) {
          my $want = render_std_json($C->{std}{$sp->{id}} || []);
          my $have = substr($line, $sp->{start}, $sp->{len});
          next if $want eq $have;
          $mm++; $first //= "$sp->{id}: " . first_diff($want, $have);
        }
      }
      $add->('configurator: const MODELS std', scalar @cids, $mm, $first);
    }
  }
  # 2. tools/STD_DATA.js
  {
    my $p = "$repo/tools/STD_DATA.js"; my $mm = 0; my $first;
    if (-f $p) {
      my $t = slurp_text($p);
      if ($t =~ /const WB_STD = (\{.*\});\s*$/s) {
        my $W = JSON::PP->new->decode($1); my $J = JSON::PP->new->canonical;
        for my $id (@ids) {
          my $want = $J->encode([ map { { h => $_->{h}, items => [ map { my %e = (t => $_->{t}); $e{tag} = $_->{tag} if defined $_->{tag} && length $_->{tag}; \%e } @{ $_->{items} } ] } } @{ $C->{std}{$id} || [] } ]);
          my $have = $J->encode($W->{$id} || []);
          next if $want eq $have; $mm++; $first //= "$id: " . first_diff($want, $have);
        }
        my @extra = grep { !$C->{by_id}{$_} } keys %$W;
        if (@extra) { $mm += @extra; $first //= 'STD_DATA models not in LINEUP: ' . join(',', sort @extra) }
      } else { $mm = scalar @ids; $first = 'const WB_STD not found' }
    } else { $mm = scalar @ids; $first = 'file missing' }
    $add->('tools/STD_DATA.js', scalar @ids, $mm, $first);
  }
  # 3-5. model pages
  {
    my ($mm_std, $mm_spec, $mm_desc) = (0, 0, 0); my ($f_std, $f_spec, $f_desc);
    for my $m (@{ $C->{lineup} }) {
      my $id = $m->{model_id}; my $slug = $m->{page_slug};
      my $p = "$repo/models/$slug/index.html";
      unless (-f $p) { $mm_std++; $mm_spec++; $mm_desc++; $f_std //= "$id: page missing"; $f_spec //= "$id: page missing"; $f_desc //= "$id: page missing"; next }
      my $h = slurp_text($p);
      # standard features grid (inside STD markers if present, else the bare line)
      my $want = render_stdgrid($C->{std}{$id} || []);
      my @grid = $h =~ /^[ \t]*<!-- STD:\Q$slug\E -->\n[ \t]*(<div class="stdgrid">.*?<\/div>)\n[ \t]*<!-- \/STD -->$/mg;
      @grid = $h =~ /^[ \t]*(<div class="stdgrid">.*<\/div>)$/mg unless @grid;
      if (@grid != 1) { $mm_std++; $f_std //= "$id: stdgrid count " . scalar(@grid) }
      elsif ($grid[0] ne $want) { $mm_std++; $f_std //= "$id: " . first_diff($want, $grid[0]) }
      # SPECS block
      my $sb = $C->{specs}{$id} ? render_specs_block($slug, $C->{specs}{$id}, $C->{desc}{$id} || {}) : undef;
      my @blk = $h =~ /^([ \t]*<!-- SPECS:\Q$slug\E -->.*?<!-- \/SPECS -->)/msg;
      if (!defined $sb) { $mm_spec++; $f_spec //= "$id: no SPECS rows in canon" }
      elsif (@blk != 1) { $mm_spec++; $f_spec //= "$id: SPECS block count " . scalar(@blk) }
      elsif ($blk[0] ne $sb) { $mm_spec++; $f_spec //= "$id: " . first_diff($sb, $blk[0]) }
      # tagline + intro
      my $d = $C->{desc}{$id} || {};
      my @tag = $h =~ /<!-- DESC:\Q$slug\E:tagline -->(.*?)<!-- \/DESC -->/g;
      @tag = $h =~ /(<div class="tag">.*?<\/div>)/g unless @tag;
      my @intro = $h =~ /^[ \t]*<!-- DESC:\Q$slug\E:intro -->\n[ \t]*(.*?)\n[ \t]*<!-- \/DESC -->$/mg;
      @intro = $h =~ /<\/figure>\n[ \t]*(<p style="font-size:16px; line-height:1.7;">.*?<\/p>)/g unless @intro;
      my $wt = tagline_html(defined $d->{tagline} ? $d->{tagline} : ''); my $wi = intro_html(defined $d->{page_intro} ? $d->{page_intro} : '');
      if (@tag != 1 || @intro != 1) { $mm_desc++; $f_desc //= "$id: tagline count " . scalar(@tag) . ', intro count ' . scalar(@intro) }
      elsif ($tag[0] ne $wt) { $mm_desc++; $f_desc //= "$id tagline: " . first_diff($wt, $tag[0]) }
      elsif ($intro[0] ne $wi) { $mm_desc++; $f_desc //= "$id intro: " . first_diff($wi, $intro[0]) }
    }
    $add->('model pages: standard features grid', scalar @ids, $mm_std, $f_std);
    $add->('model pages: SPECS block', scalar @ids, $mm_spec, $f_spec);
    $add->('model pages: tagline + intro', scalar @ids, $mm_desc, $f_desc);
  }
  # 6. tools/SPEC_DATA.js
  {
    my $p = "$repo/tools/SPEC_DATA.js"; my $want = render_spec_data_js($C);
    if (-f $p) { my $have = slurp_text($p); $add->('tools/SPEC_DATA.js', 1, $have eq $want ? 0 : 1, $have eq $want ? '' : first_diff($want, $have)) }
    else { $add->('tools/SPEC_DATA.js', 1, 1, 'file missing') }
  }
  return \@R;
}

