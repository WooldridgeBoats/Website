#!/usr/bin/perl
# gen_preowned.pl - the pre-owned listings: one page per boat, plus the cards on /pre-owned/.
#
#   perl _build/gen_preowned.pl            # write everything
#   perl _build/gen_preowned.pl --check    # report what would change, write nothing
#
# THE DATA IS _build/preowned.json - edit that, run this, commit. Nothing on the pages
# is edited by hand (2026-10-28).
#
# What it writes:
#   pre-owned/<slug>/index.html   one page per listed boat: the seller's write-up, the facts,
#                                 the seller's contact details, every photo (shared viewer)
#   pre-owned/index.html          the cards between <!-- PREOWNED-GRID --> markers; each card
#                                 opens the boat's page (the whole card is the link)
# Then it chains stamp_assets.pl, gen_canonicals.pl and gen_sitemap.pl, because a new
# page needs a hash-stamped stylesheet, a canonical and a sitemap entry.
#
# A boat marked sold:true, or removed from the list, has its page folder deleted - but ONLY
# a folder whose index.html carries this script's GENERATED marker. A hand-made page under
# pre-owned/ is never touched.
#
# Header and footer are baked in from header.html / footer.html exactly as inject_partials.pl
# does, inside the same PARTIAL markers, so a later inject run keeps them current.
#
# Why pages, not the old grid-with-lightbox: a card used to open a photo viewer and nothing
# else, so a listing had no address to share, no room for the seller's write-up and nothing
# for Google to index (Stephen, 2026-10-28). Photos stay where they were:
# assets/preowned/<slug>/NN.jpg + thumbs/NN.jpg.
use strict;
use warnings;
use File::Basename qw(dirname);
use File::Path qw(make_path remove_tree);
use Cwd qw(abs_path);
use JSON::PP;

my $check_only = grep { $_ eq '--check' } @ARGV;
my $root = dirname(dirname(abs_path(__FILE__)));
my $DATA = "$root/_build/preowned.json";
my $GRID = "$root/pre-owned/index.html";
my $MARK = '<!-- GENERATED by _build/gen_preowned.pl from _build/preowned.json - edit those, never this file -->';

sub slurp { my ($f) = @_; open my $fh, '<:raw', $f or die "can't read $f: $!"; local $/; my $d = <$fh>; close $fh; $d }
sub spew  { my ($f, $d) = @_; open my $fh, '>:raw', $f or die "can't write $f: $!"; print $fh $d; close $fh }

# JSON is UTF-8 on disk; pages are written as ASCII with entities so no editor can mangle them
my $json = JSON::PP->new->utf8->relaxed;
my $cfg  = $json->decode(slurp($DATA));
my @all  = @{ $cfg->{listings} || [] };
die "no listings in $DATA\n" unless @all;

sub esc {
  my ($s) = @_;
  $s = '' unless defined $s;
  $s =~ s/&/&amp;/g; $s =~ s/</&lt;/g; $s =~ s/>/&gt;/g; $s =~ s/"/&quot;/g;
  $s =~ s/([^\x00-\x7f])/sprintf('&#%d;', ord $1)/ge;
  $s;
}
sub nn { sprintf '%02d', $_[0] }

# header / footer, exactly as inject_partials.pl bakes them
my $header = slurp("$root/header.html");
my $footer = slurp("$root/footer.html");

# ---------------------------------------------------------------------------
# sanity: every listed boat has its photos
# ---------------------------------------------------------------------------
my @live = grep { !$_->{sold} } @all;
my @problems;
for my $b (@all) {
  push @problems, "$b->{slug}: no slug"  unless $b->{slug};
  push @problems, "$b->{slug}: slug must be lower-case letters, digits and dashes" if $b->{slug} && $b->{slug} !~ /^[a-z0-9-]+$/;
  next if $b->{sold};
  for my $f (qw(yr len model price)) { push @problems, "$b->{slug}: $f is empty" unless defined $b->{$f} && length $b->{$f} }
  push @problems, "$b->{slug}: n (photo count) missing" unless $b->{n};
  for my $i (1 .. ($b->{n} || 0)) {
    my $p = "$root/assets/preowned/$b->{slug}/" . nn($i) . '.jpg';
    push @problems, "$b->{slug}: missing photo $p" unless -f $p;
    push @problems, "$b->{slug}: missing thumb for " . nn($i) unless -f "$root/assets/preowned/$b->{slug}/thumbs/" . nn($i) . '.jpg';
  }
}
if (@problems) { print "  ! $_\n" for @problems; die "fix _build/preowned.json first - nothing written\n" }

# ---------------------------------------------------------------------------
# the pieces every page shares
# ---------------------------------------------------------------------------
sub label  { my ($b) = @_; "$b->{yr} Wooldridge " . esc($b->{model}) }                    # viewer caption
sub title  { my ($b) = @_; "$b->{yr} $b->{len}&prime; " . esc($b->{model}) }               # headings
sub plain  { my ($b) = @_; "$b->{yr} $b->{len}' $b->{model}" }                              # <title>, alt text (no entities)
sub page   { my ($b) = @_; "/pre-owned/$b->{slug}/" }
sub photo  { my ($b, $i) = @_; "/assets/preowned/$b->{slug}/" . nn($i) . '.jpg' }
sub thumb  { my ($b, $i) = @_; "/assets/preowned/$b->{slug}/thumbs/" . nn($i) . '.jpg' }

sub contact_bits {
  my ($b) = @_;
  my @c;
  push @c, '<b>' . esc($b->{contact}) . '</b>' if $b->{contact};
  if ($b->{phone}) { (my $tel = $b->{phone}) =~ s/[^\d+]//g; push @c, '<a href="tel:' . esc($tel) . '">' . esc($b->{phone}) . '</a>' }
  push @c, '<a href="mailto:' . esc($b->{email}) . '">' . esc($b->{email}) . '</a>' if $b->{email};
  @c;
}

# the seller's write-up; the one-line note stands in where no write-up was recovered
sub paragraphs {
  my ($b) = @_;
  my @p = grep { defined && length } @{ $b->{desc} || [] };
  @p = ($b->{note}) if !@p && $b->{note};
  @p;
}

# ---------------------------------------------------------------------------
# one card on /pre-owned/
# ---------------------------------------------------------------------------
sub card {
  my ($b) = @_;
  my $href = page($b);
  my $alt  = esc(plain($b)) . ' - photo 1';
  my @specs;
  push @specs, '<span><b>Engine:</b> '   . esc($b->{eng})     . '</span>' if $b->{eng};
  push @specs, '<span><b>Hours:</b> '    . esc($b->{hours})   . '</span>' if $b->{hours};
  push @specs, '<span><b>Trailer:</b> '  . esc($b->{trailer}) . '</span>' if $b->{trailer};
  push @specs, '<span><b>Location:</b> ' . esc($b->{loc})     . '</span>' if $b->{loc};
  push @specs, '<span>' . esc($b->{note}) . '</span>' if $b->{note};
  my @c = contact_bits($b);
  push @specs, '<span><b>Seller:</b> ' . join(' &middot; ', @c) . '</span>' if @c;
  return join '',
    '<article class="inv polist" data-href="' . $href . '">',
      '<a class="invph" href="' . $href . '" aria-label="' . esc(plain($b)) . ' - open the listing"><span class="badge in">Available</span>',
        '<img src="' . photo($b, 1) . '" alt="' . $alt . '" loading="lazy"></a>',
      '<div class="ibody"><div class="iyear">' . $b->{yr} . ($b->{drive} ? ' &middot; ' . esc($b->{drive}) : '') . '</div>',
        '<h3><a href="' . $href . '">' . $b->{len} . '&prime; ' . esc($b->{model}) . '</a></h3>',
        '<div class="specs">' . join('', @specs) . '</div>',
        '<div class="irow"><span class="iprice">' . esc($b->{price}) . '</span>',
          '<a class="ilink" href="' . $href . '">' . $b->{n} . ' photo' . ($b->{n} == 1 ? '' : 's') . ' &middot; View listing &rsaquo;</a></div></div>',
    '</article>';
}

# ---------------------------------------------------------------------------
# one boat's page
# ---------------------------------------------------------------------------
sub boat_page {
  my ($b) = @_;
  my $t     = title($b);
  my $lab   = label($b);
  my @paras = paragraphs($b);
  my $meta  = @paras ? $paras[0] : plain($b) . ' for sale, owner-listed.';
  $meta = substr($meta, 0, 157) . '...' if length $meta > 160;

  my @facts = (
    ['Price',    $b->{price},   'price'],
    ['Year',     $b->{yr}],
    ['Length',   $b->{len} . ' <i>ft</i>', '', 1],
    ['Drive',    $b->{drive}],
    ['Engine',   $b->{eng}],
    ['Hours',    $b->{hours}],
    ['Trailer',  $b->{trailer}],
    ['Location', $b->{loc}],
  );
  my $facts = join '', map {
    my ($l, $v, $cls, $raw) = @$_;
    (defined $v && length $v)
      ? '<div class="fact' . ($cls ? " $cls" : '') . '"><div class="l">' . $l . '</div><div class="v">' . ($raw ? $v : esc($v)) . '</div></div>'
      : ''
  } @facts;

  my @c = contact_bits($b);
  my $seller = @c
    ? '<div class="infocard poseller"><h3>Seller contact</h3><p>' . join(' &nbsp;&middot;&nbsp; ', @c) . '</p>'
      . '<p class="pofine">This boat is owner-listed: the seller above is the person to contact about it. '
      . 'Questions about Wooldridge boats in general? <a href="/contact/">Contact the factory</a>.</p></div>'
    : '<div class="infocard poseller"><h3>Seller contact</h3><p class="pofine">This listing did not include contact details. '
      . '<a href="/contact/">Contact the factory</a> and we will put you in touch.</p></div>';

  my $desc = join '', map { '<p>' . esc($_) . '</p>' } @paras;

  my $hero = '<div class="gallery pohero"><a href="' . photo($b, 1) . '" data-m="' . $lab . '" aria-label="' . esc(plain($b)) . ' - photo 1 of ' . $b->{n} . '">'
           . '<img src="' . photo($b, 1) . '" alt="' . esc(plain($b)) . ' - photo 1" fetchpriority="high"></a></div>';
  my $grid = '';
  for my $i (2 .. $b->{n}) {
    $grid .= '<a href="' . photo($b, $i) . '" data-m="' . $lab . '" aria-label="' . esc(plain($b)) . ' - photo ' . $i . ' of ' . $b->{n} . '">'
           . '<img src="' . thumb($b, $i) . '" alt="' . esc(plain($b)) . ' - photo ' . $i . '" loading="lazy"></a>';
  }
  my $gallery = $b->{n} > 1
    ? '<div class="sechead tight"><h2 style="font-size:clamp(20px,2.6vw,28px);">Photos</h2><div class="eyebrow">' . $b->{n} . ' photos &middot; click any to view full size</div></div>'
      . '<div class="gallery pogal">' . $grid . '</div>'
    : '';

  my $crumb_name = esc("$b->{yr} $b->{model}");
  return <<"HTML";
<!DOCTYPE html>
<html lang="en">
<head>
$MARK
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>@{[ esc(plain($b)) ]} &mdash; Pre-Owned &mdash; Wooldridge Boats</title>
<meta name="description" content="@{[ esc($meta) ]}">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Inter:wght@200;300;400;500;600;700;800&display=swap" rel="stylesheet">
<link rel="stylesheet" href="/house.css">
<link rel="canonical" href="https://www.wooldridgeboats.com@{[ page($b) ]}">
<style>
  /* the lead photo: one big card, not a 4-up grid; it and the thumbs below feed the shared viewer */
  .pohero{ display:block; max-width:980px; margin:0 auto 26px; }
  .pohero img{ aspect-ratio:16/10; }
  .invdesc{ max-width:840px; margin:0 auto 6px; }
  .invdesc p{ font-size:16px; line-height:1.75; margin-bottom:14px; }
  .poseller{ max-width:720px; margin:26px auto 0; text-align:center; }
  .poseller p{ font-size:15px; margin:8px 0 0; }
  .poseller .pofine{ font-size:13px; color:var(--muted); margin-top:12px; }
  .pogal{ grid-template-columns:repeat(4,1fr); }
  \@media (max-width:760px){ .pogal{ grid-template-columns:repeat(2,1fr); } }
</style>
<link rel="icon" href="/favicon.ico" sizes="any">
<link rel="icon" type="image/png" sizes="32x32" href="/assets/brand/favicon-32.png">
<link rel="icon" type="image/png" sizes="16x16" href="/assets/brand/favicon-16.png">
<link rel="apple-touch-icon" sizes="180x180" href="/assets/brand/favicon-180.png">
</head>
<body>
<!-- PARTIAL:header -->
$header<!-- /PARTIAL:header -->
<main>
<header class="pagemast"><div class="wrap">
  <div class="co">Wooldridge Boats &nbsp;&middot;&nbsp; Seattle, Washington</div>
  <div class="crumb"><a href="/">HOME</a> / <a href="/pre-owned/">PRE-OWNED</a> / $crumb_name</div>
  <h1>$t</h1><div class="kick">OWNER-LISTED PRE-OWNED BOAT</div><div class="tag">@{[ esc($b->{price}) ]}@{[ $b->{loc} ? ' &nbsp;&middot;&nbsp; ' . esc($b->{loc}) : '' ]}</div>
  <div class="dbl mastrule"></div>
</div></header>
<section class="pagebody"><div class="wrap">
  $hero
  <div class="invdesc">$desc</div>
  <div class="factrow">$facts</div>
  $seller
  $gallery
  <div class="modelctas"><a class="plate ghost" href="/pre-owned/">&lsaquo; All Pre-Owned Boats</a><a class="plate ghost" href="/sell-your-boat/">Sell Your Wooldridge</a></div>
</div></section>
</main>
<!-- PARTIAL:footer -->
$footer<!-- /PARTIAL:footer -->
<script src="/assets/shop.js"></script>
<script src="/assets/gallery.js" defer></script>
<script src="/assets/pagenav.js" defer></script>
</body>
</html>
HTML
}

# ---------------------------------------------------------------------------
# write
# ---------------------------------------------------------------------------
my ($wrote, $same, $removed) = (0, 0, 0);
sub put {
  my ($path, $body) = @_;
  if (-f $path && slurp($path) eq $body) { $same++; return }
  $wrote++;
  print(($check_only ? 'would write: ' : 'wrote: ') . substr($path, length($root) + 1) . "\n");
  return if $check_only;
  make_path(dirname($path));
  spew($path, $body);
}

# the boats' pages
my %keep;
for my $b (@live) {
  $keep{$b->{slug}} = 1;
  put("$root/pre-owned/$b->{slug}/index.html", boat_page($b));
}

# retired boats: only folders this script made
opendir my $dh, "$root/pre-owned" or die "no pre-owned/: $!";
for my $d (sort grep { !/^\./ && -d "$root/pre-owned/$_" } readdir $dh) {
  next if $keep{$d};
  my $ix = "$root/pre-owned/$d/index.html";
  if (-f $ix && index(slurp($ix), $MARK) >= 0) {
    $removed++;
    print(($check_only ? 'would remove: ' : 'removed: ') . "pre-owned/$d/ (no longer listed, or sold)\n");
    remove_tree("$root/pre-owned/$d") unless $check_only;
  } else {
    print "left alone: pre-owned/$d/ (not generated by this script)\n";
  }
}
closedir $dh;

# the cards on /pre-owned/
my $grid_html = slurp($GRID);
my $cards = "<!-- PREOWNED-GRID -->\n$MARK\n"
          . '<div class="listing-grid" id="grid">' . "\n" . join("\n", map { card($_) } @live) . "\n</div>\n"
          . '<!-- /PREOWNED-GRID -->';
$grid_html =~ s{<!-- PREOWNED-GRID -->.*?<!-- /PREOWNED-GRID -->}{$cards}s
  or die "pre-owned/index.html has no <!-- PREOWNED-GRID --> ... <!-- /PREOWNED-GRID --> markers\n";
put($GRID, $grid_html);

printf "\n%d live listing(s), %d sold/skipped; %d file(s) %s, %d unchanged, %d folder(s) removed\n",
  scalar(@live), scalar(@all) - scalar(@live), $wrote, ($check_only ? 'would change' : 'written'), $same, $removed;

exit 0 if $check_only;

# a new page needs its stylesheet stamped, a canonical and a sitemap line
for my $step (qw(stamp_assets.pl gen_canonicals.pl gen_sitemap.pl)) {
  print "\n== $step ==\n";
  my @cmd = ('perl', "$root/_build/$step");
  push @cmd, $root if $step eq 'stamp_assets.pl';
  system(@cmd) == 0 or die "$step failed\n";
}
